func TestDeepWikiCollectionStateTransitions(t *testing.T) {
	t.Parallel()
	repository := seededWikiStore(t)
	service := NewDeepWikiService(repository, &capturingProvider{response: "# page"})

	if got := service.Collection().Status; got != domain.DeepWikiNotGenerated {
		t.Fatalf("initial status = %q, want not_generated", got)
	}

	if _, err := service.Generate(context.Background()); err != nil {
		t.Fatalf("Generate() error = %v", err)
	}
	collection := service.Collection()
	if collection.Status != domain.DeepWikiReady || len(collection.Pages) == 0 || collection.SnapshotID == "" {
		t.Fatalf("after generate = %#v, want ready with pages and snapshot", collection)
	}

	// Mutating the index makes the published pages stale.
	addFile(repository, "extra.go")
	if got := service.Collection().Status; got != domain.DeepWikiStale {
		t.Fatalf("after index change status = %q, want stale", got)
	}
}

func TestDeepWikiConcurrentRefreshRejected(t *testing.T) {
	t.Parallel()
	repository := seededWikiStore(t)
	provider := &blockingProvider{response: "# page", release: make(chan struct{}), entered: make(chan struct{})}
	service := NewDeepWikiService(repository, provider)

	done := make(chan error, 1)
	go func() {
		_, err := service.Generate(context.Background())
		done <- err
	}()
	<-provider.entered // the first generation is now in progress

	if got := service.Collection().Status; got != domain.DeepWikiGenerating {
		t.Fatalf("status during generation = %q, want generating", got)
	}
	if _, err := service.Generate(context.Background()); !errors.Is(err, ErrGenerationInProgress) {
		t.Fatalf("concurrent Generate() error = %v, want ErrGenerationInProgress", err)
	}

	close(provider.release)
	if err := <-done; err != nil {
		t.Fatalf("first Generate() error = %v", err)
	}
}

func TestDeepWikiObsoleteSnapshotNotPublished(t *testing.T) {
	t.Parallel()
	repository := seededWikiStore(t)
	if _, err := NewDeepWikiService(repository, &capturingProvider{response: "# base"}).Generate(context.Background()); err != nil {
		t.Fatalf("baseline Generate() error = %v", err)
	}

	service := NewDeepWikiService(repository, &mutatingProvider{store: repository, response: "# obsolete"})
	if _, err := service.Generate(context.Background()); !errors.Is(err, ErrSnapshotChanged) {
		t.Fatalf("Generate() error = %v, want ErrSnapshotChanged", err)
	}
	// The previous valid pages must remain.
	for _, page := range service.Pages() {
		if page.Markdown == "# obsolete" {
			t.Fatal("obsolete result was published as current")
		}
	}
	if len(service.Pages()) == 0 {
		t.Fatal("previous pages were lost")
	}
}

func TestDeepWikiFailedRefreshPreservesPages(t *testing.T) {
	t.Parallel()
	repository := seededWikiStore(t)
	if _, err := NewDeepWikiService(repository, &capturingProvider{response: "# base"}).Generate(context.Background()); err != nil {
		t.Fatalf("baseline Generate() error = %v", err)
	}

	service := NewDeepWikiService(repository, &capturingProvider{err: errors.New("LLM offline")})
	if _, err := service.Generate(context.Background()); err == nil {
		t.Fatal("Generate() succeeded with a failing provider; want error")
	}
	collection := service.Collection()
	if collection.Status != domain.DeepWikiFailed {
		t.Fatalf("status = %q, want failed", collection.Status)
	}
	if len(collection.Pages) == 0 {
		t.Fatal("failed refresh wiped previously valid pages")
	}
	if collection.LastError == "" {
		t.Fatal("failed refresh did not record an error")
	}
}

