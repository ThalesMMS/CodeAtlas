func seededWikiStore(t *testing.T) repository.Store {
	t.Helper()
	repository, err := repository.OpenJSON(filepath.Join(t.TempDir(), "index.json"))
	if err != nil {
		t.Fatal(err)
	}
	repository.ReplaceFile(domain.ParsedFile{
		File: domain.File{Path: "main.go", Language: "go", Hash: "main", IndexedAt: time.Now()},
		Symbols: []domain.Symbol{
			{ID: "file", Path: "main.go", Name: "main.go", QualifiedName: "main.go", Kind: "file",
				Range: domain.Range{Start: domain.Position{Line: 1, Column: 1}, End: domain.Position{Line: 3, Column: 1}}, Summary: "Main file."},
			{ID: "main", Path: "main.go", Name: "main", QualifiedName: "main.go::main", Kind: "function",
				Range: domain.Range{Start: domain.Position{Line: 3, Column: 1}, End: domain.Position{Line: 3, Column: 14}}, Summary: "Entry point."},
		},
	})
	return repository
}

func addFile(repository repository.Store, path string) {
	repository.ReplaceFile(domain.ParsedFile{
		File: domain.File{Path: path, Language: "go", Hash: path, IndexedAt: time.Now()},
		Symbols: []domain.Symbol{
			{ID: path + ":file", Path: path, Name: path, QualifiedName: path, Kind: "file",
				Range: domain.Range{Start: domain.Position{Line: 1, Column: 1}, End: domain.Position{Line: 2, Column: 1}}, Summary: "extra"},
		},
	})
}

// blockingProvider blocks inside Complete until released, signalling first entry.
type blockingProvider struct {
	response string
	release  chan struct{}
	entered  chan struct{}
	once     sync.Once
}

func (p *blockingProvider) Name() string    { return "capture" }
func (p *blockingProvider) Available() bool { return true }
func (p *blockingProvider) Complete(_ context.Context, systemPrompt, _ string, _ int) (string, error) {
	p.once.Do(func() { close(p.entered) })
	<-p.release
	return structuredStub(systemPrompt, p.response), nil
}
func (p *blockingProvider) Embed(context.Context, []string) ([][]float64, error) {
	return nil, errors.New("disabled")
}

// mutatingProvider changes the index during the first Complete call, simulating a
// concurrent index update that makes the in-flight generation obsolete.
type mutatingProvider struct {
	store    repository.Store
	response string
	once     sync.Once
}

func (p *mutatingProvider) Name() string    { return "capture" }
func (p *mutatingProvider) Available() bool { return true }
func (p *mutatingProvider) Complete(_ context.Context, systemPrompt, _ string, _ int) (string, error) {
	p.once.Do(func() { addFile(p.store, "mutated.go") })
	return structuredStub(systemPrompt, p.response), nil
}
func (p *mutatingProvider) Embed(context.Context, []string) ([][]float64, error) {
	return nil, errors.New("disabled")
}

func TestDeepWikiGeneratesPagesWithProviderMetadata(t *testing.T) {
	t.Parallel()
	repository, err := repository.OpenJSON(filepath.Join(t.TempDir(), "index.json"))
	if err != nil {
		t.Fatal(err)
	}
	repository.ReplaceFile(domain.ParsedFile{
		File: domain.File{Path: "main.go", Language: "go", Hash: "main", IndexedAt: time.Now()},
		Symbols: []domain.Symbol{
			{
				ID: "file", Path: "main.go", Name: "main.go", QualifiedName: "main.go", Kind: "file",
				Range:   domain.Range{Start: domain.Position{Line: 1, Column: 1}, End: domain.Position{Line: 3, Column: 1}},
				Summary: "Main file.",
			},
			{
				ID: "main", Path: "main.go", Name: "main", QualifiedName: "main.go::main", Kind: "function",
				Range:   domain.Range{Start: domain.Position{Line: 3, Column: 1}, End: domain.Position{Line: 3, Column: 14}},
				Summary: "Entry point.",
			},
		},
	})

	provider := &capturingProvider{response: "# Page generated by the LLM"}
	service := NewDeepWikiService(repository, provider)
	pages, err := service.Generate(context.Background())
	if err != nil {
		t.Fatalf("Generate() error = %v", err)
	}
	if len(pages) == 0 {
		t.Fatal("Generate() returned no pages")
	}
	for _, page := range pages {
		if page.Provider != provider.Name() {
			t.Fatalf("page %q provider = %q, want %q", page.Slug, page.Provider, provider.Name())
		}
		// The page is now rendered server-side from the structured WikiPageContent,
		// so the LLM text appears inside the rendered Markdown.
		if page.Archetype != "glossary" && !strings.Contains(page.Markdown, provider.response) {
			t.Fatalf("page %q markdown = %q, want rendered LLM content", page.Slug, page.Markdown)
		}
		if page.OutputSchemaVersion != "wiki-page/v4" {
			t.Fatalf("page %q output schema = %q, want wiki-page/v4", page.Slug, page.OutputSchemaVersion)
		}
		if page.Archetype != "glossary" {
			if page.Diagram == nil || page.Diagram.Version != "mermaid/v1" || page.Diagram.Source == "" {
				t.Fatalf("page %q deterministic diagram = %+v", page.Slug, page.Diagram)
			}
			if !strings.Contains(page.Markdown, "```mermaid\n") || !strings.Contains(page.Markdown, "**Diagram sources:**") {
				t.Fatalf("page %q Markdown lacks rendered diagram/sources: %q", page.Slug, page.Markdown)
			}
		}
	}
	for index := range provider.userPrompts {
		if strings.Contains(provider.userPrompts[index], "graph TD") || strings.Contains(provider.systemPrompts[index], "mermaid") {
			t.Fatalf("deterministic diagram leaked into model request %d", index)
		}
	}
}

