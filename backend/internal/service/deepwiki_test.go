func TestDeepWikiReturnsProviderErrorInsteadOfDraftPage(t *testing.T) {
	t.Parallel()
	repository, err := repository.OpenJSON(filepath.Join(t.TempDir(), "index.json"))
	if err != nil {
		t.Fatal(err)
	}
	repository.ReplaceFile(domain.ParsedFile{
		File: domain.File{Path: "main.go", Language: "go", Hash: "main", IndexedAt: time.Now()},
		Symbols: []domain.Symbol{
			{
				ID: "file", Path: "main.go", Name: "main.go", QualifiedName: "main.go", Kind: "file",
				Range:   domain.Range{Start: domain.Position{Line: 1, Column: 1}, End: domain.Position{Line: 3, Column: 1}},
				Summary: "Main file.",
			},
		},
	})

	service := NewDeepWikiService(repository, &capturingProvider{err: errors.New("LLM returned an empty response")})
	_, err = service.Generate(context.Background())
	if err == nil {
		t.Fatal("Generate() succeeded with a failing provider; want error")
	}
	appErr, ok := apperror.As(err)
	if !ok || appErr.Code != apperror.CodeProviderUnavailable {
		t.Fatalf("error = %v, want PROVIDER_UNAVAILABLE app error", err)
	}
	if appErr.Cause == nil || !strings.Contains(appErr.Cause.Error(), "LLM returned an empty response") {
		t.Fatalf("provider cause not preserved: %v", appErr.Cause)
	}
	if pages := service.Pages(); len(pages) != 0 {
		t.Fatalf("Pages() = %#v, want no draft pages persisted", pages)
	}
}

