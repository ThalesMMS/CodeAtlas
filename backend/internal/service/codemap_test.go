type countingSnapshotStore struct {
	repository.Store
	snapshots int
}

func (s *countingSnapshotStore) Snapshot() repository.ReadView {
	s.snapshots++
	return s.Store.Snapshot()
}
func (s *countingSnapshotStore) SnapshotContext(ctx context.Context) (repository.ReadView, error) {
	s.snapshots++
	return s.Store.SnapshotContext(ctx)
}

func TestCodemapHonorsNodeBudgetAndKeepsValidEdges(t *testing.T) {
	t.Parallel()
	repository, err := repository.OpenSQLite(context.Background(), repository.SQLiteConfig{WorkspaceRoot: t.TempDir()})
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = repository.Close() })
	engine := codeparser.New()
	indexSource(t, repository, engine, "internal/order/service.go", `package order

type Service struct{}
func (s *Service) Submit() { validateOrder(); Save() }
func validateOrder() {}
func Save() {}
`)
	indexSource(t, repository, engine, "web/checkout.ts", `export class Checkout {
  completeCheckout() { submitOrder() }
}
function submitOrder() {}
`)

	provider := &capturingProvider{response: "## Map generated by the LLM"}
	countingStore := &countingSnapshotStore{Store: repository}
	retriever := retrieval.NewHybrid(countingStore, ai.Disabled{}, false)
	service := NewCodemapService(countingStore, retriever, provider)
	result, err := service.Generate(context.Background(), domain.CodemapRequest{
		Query:    "checkout submit order service save",
		MaxNodes: 8,
	})
	if err != nil {
		t.Fatalf("Generate() error = %v", err)
	}
	if len(result.Nodes) > 8 {
		t.Fatalf("Generate() returned %d nodes, budget is 8", len(result.Nodes))
	}
	if result.Provider != provider.Name() {
		t.Fatalf("provider = %q, want %q", result.Provider, provider.Name())
	}
	if countingStore.snapshots != 1 {
		t.Fatalf("Codemap Snapshot calls = %d, want one pinned view", countingStore.snapshots)
	}
	nodeIDs := make(map[string]struct{}, len(result.Nodes))
	for _, node := range result.Nodes {
		nodeIDs[node.ID] = struct{}{}
	}
	for _, edge := range result.Edges {
		if _, ok := nodeIDs[edge.Source]; !ok {
			t.Fatalf("edge source %q has no node", edge.Source)
		}
		if _, ok := nodeIDs[edge.Target]; !ok {
			t.Fatalf("edge target %q has no node", edge.Target)
		}
	}
}

