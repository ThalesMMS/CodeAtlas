type capturingProvider struct {
	mu            sync.Mutex
	response      string
	structured    string
	err           error
	systemPrompt  string
	userPrompt    string
	systemPrompts []string
	userPrompts   []string
	maxTokens     int
}

func (p *capturingProvider) Name() string { return "capture" }

func (p *capturingProvider) Available() bool { return true }

func (p *capturingProvider) Complete(_ context.Context, systemPrompt, userPrompt string, maxTokens int) (string, error) {
	p.mu.Lock()
	p.systemPrompt = systemPrompt
	p.userPrompt = userPrompt
	p.systemPrompts = append(p.systemPrompts, systemPrompt)
	p.userPrompts = append(p.userPrompts, userPrompt)
	if maxTokens > p.maxTokens {
		p.maxTokens = maxTokens
	}
	err := p.err
	structured := p.structured
	response := p.response
	p.mu.Unlock()
	if err != nil {
		return "", err
	}
	if structured != "" {
		return structured, nil
	}
	return structuredStub(systemPrompt, response), nil
}

// structuredStub returns the minimal valid structured output for whichever schema
// the system prompt requests (no cited evidence IDs → trivially grounded), with
// the configured response carried as the human-visible text. A non-structured
// prompt returns response unchanged.
func structuredStub(systemPrompt, response string) string {
	switch {
	case strings.Contains(systemPrompt, "explanation/v2"):
		summary := response
		if summary == "" {
			summary = "summary"
		}
		return `{"schemaVersion":"explanation/v2","summary":` + strconv.Quote(summary) + `,"observations":[],"inferences":[],"uncertainties":[],"changeImpact":[]}`
	case strings.Contains(systemPrompt, "codemap-narrative/v2"):
		overview := response
		if overview == "" {
			overview = "The generated map explains the grounded execution flow and its observed source boundaries."
		}
		overview += " It names the participating components, the observed boundaries, and the scope supported by indexed evidence."
		motivation := strings.Repeat("The application keeps transport, business rules, and persistence responsibilities separate so callers can follow each boundary in the observed code. ", 2)
		details := strings.Repeat("The grounded path starts at the selected entrypoint, follows validated local calls, records state changes supported by snippets, and ends at the observed repository boundary. Each step remains tied to backend-owned source bytes. ", 2)
		return `{"schemaVersion":"codemap-narrative/v2","title":"Map","overview":` + strconv.Quote(overview) + `,"motivation":` + strconv.Quote(motivation) + `,"details":` + strconv.Quote(details) + `,"trace":[],"flows":[],"claims":[],"inferences":[],"uncertainties":[]}`
	case strings.Contains(systemPrompt, "wiki-page/v4"):
		text := response
		if text == "" {
			text = "Content"
		}
		return `{"schemaVersion":"wiki-page/v4","title":` + strconv.Quote(text) + `,"sections":[{"heading":` + strconv.Quote(text) + `,"claims":[]}],"relatedPages":[],"inferences":[],"limitations":[]}`
	default:
		return response
	}
}

